#!/usr/bin/env node

import { gzipSync } from 'node:zlib';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('Usage: node tools/embed-bergamot-wasm.mjs <input.wasm> <output.js>');
  process.exitCode = 2;
} else {
  const wasm = readFileSync(resolve(input));
  const compressed = gzipSync(wasm, { level: 9 });
  const base64 = compressed.toString('base64');
  const chunks = base64.match(/.{1,120}/g) || [];
  const source = `/* Generated by tools/embed-bergamot-wasm.mjs. Do not edit. */\n` +
    `/* Bergamot Translator v0.6.0, MPL-2.0. See NOTICE.md and LICENSE.txt. */\n` +
    `globalThis.MORPHEUS_BERGAMOT_WASM_GZIP_BASE64 = [\n` +
    chunks.map(chunk => `  '${chunk}'`).join(',\n') +
    `\n].join('');\n`;
  writeFileSync(resolve(output), source);
  console.log(`Embedded ${wasm.length} bytes as ${compressed.length} gzip bytes.`);
}
